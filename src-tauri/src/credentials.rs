use async_trait::async_trait;
use keyring::Entry;

use crate::keys::derive_account_id;
use catbird_mls::orchestrator::credentials::CredentialStore;
use catbird_mls::orchestrator::error::{OrchestratorError, Result};

pub const SERVICE_NAME: &str = "blue.catbird.catmos.clean-v2-openmls-v09";
pub const KEY_SUFFIX: &str = "clean-v2-openmls-v09";

#[derive(Debug, PartialEq, Eq)]
pub enum CredentialEnrollmentState {
    Unenrolled,
    FullyEnrolled,
    Partial(String),
}

/// OS keychain-backed credential store using the `keyring` crate.
pub struct KeyringCredentialStore;

impl KeyringCredentialStore {
    pub fn new() -> Self {
        match Self::try_new() {
            Ok(store) => store,
            Err(err) => panic!("{err}"),
        }
    }

    pub fn try_new() -> Result<Self> {
        #[cfg(target_os = "android")]
        {
            Err(OrchestratorError::Credential(
                "Android secure credential storage is not implemented; refusing to initialize MLS with keyring's mock store"
                    .to_string(),
            ))
        }

        #[cfg(not(target_os = "android"))]
        {
            Ok(Self)
        }
    }

    fn entry(key: &str) -> std::result::Result<Entry, keyring::Error> {
        Entry::new(SERVICE_NAME, key)
    }

    /// The one place the account-scoped credential slot name is built. Every
    /// slot is `{slot}:{account_id}:{KEY_SUFFIX}` so a slot can never be read
    /// or written outside the exact account and storage generation.
    fn scoped_key(slot: &str, user_did: &str) -> String {
        format!("{}:{}:{}", slot, derive_account_id(user_did), KEY_SUFFIX)
    }

    pub fn key_signing(user_did: &str) -> String {
        Self::scoped_key("signing_key", user_did)
    }

    pub fn key_mls_did(user_did: &str) -> String {
        Self::scoped_key("mls_did", user_did)
    }

    pub fn key_device_uuid(user_did: &str) -> String {
        Self::scoped_key("device_uuid", user_did)
    }

    /// The UUID generated by catmos and submitted in `registerDevice`.
    ///
    /// The delivery service mints a separate `device_id`; keeping the two
    /// values under different key names prevents a server identifier from
    /// being sent back as the client UUID during device reconciliation.
    pub fn key_local_device_uuid(user_did: &str) -> String {
        Self::scoped_key("local_device_uuid", user_did)
    }

    /// The server-minted device identifier returned by device registration.
    pub fn key_server_device_id(user_did: &str) -> String {
        Self::scoped_key("server_device_id", user_did)
    }

    async fn get_string(key: String) -> Result<Option<String>> {
        match Self::entry(&key) {
            Ok(entry) => match entry.get_password() {
                Ok(value) => {
                    let trimmed = value.trim();
                    if trimmed.is_empty() {
                        Err(OrchestratorError::Credential(format!(
                            "keychain slot {key} is empty or corrupt"
                        )))
                    } else {
                        Ok(Some(value))
                    }
                }
                Err(keyring::Error::NoEntry) => Ok(None),
                Err(error) => Err(OrchestratorError::Credential(error.to_string())),
            },
            Err(error) => Err(OrchestratorError::Credential(error.to_string())),
        }
    }

    async fn store_string(key: String, value: &str) -> Result<()> {
        let value = value.trim();
        if value.is_empty() {
            return Err(OrchestratorError::Credential(
                "cannot persist an empty device identifier".to_string(),
            ));
        }
        Self::entry(&key)
            .map_err(|error| OrchestratorError::Credential(error.to_string()))?
            .set_password(value)
            .map_err(|error| OrchestratorError::Credential(error.to_string()))
    }

    fn delete_key(key: String) -> Result<()> {
        match Self::entry(&key) {
            Ok(entry) => match entry.delete_credential() {
                Ok(()) | Err(keyring::Error::NoEntry) => Ok(()),
                Err(e) => Err(OrchestratorError::Credential(e.to_string())),
            },
            Err(e) => Err(OrchestratorError::Credential(e.to_string())),
        }
    }

    /// Store the client-generated UUID independently from the server ID.
    pub async fn store_local_device_uuid(&self, user_did: &str, uuid: &str) -> Result<()> {
        Self::store_string(Self::key_local_device_uuid(user_did), uuid).await
    }

    /// Read the client-generated UUID used to correlate `listDevices` rows.
    pub async fn get_local_device_uuid(&self, user_did: &str) -> Result<Option<String>> {
        Self::get_string(Self::key_local_device_uuid(user_did)).await
    }

    /// Store the server-minted device ID separately from the local UUID.
    pub async fn store_server_device_id(&self, user_did: &str, device_id: &str) -> Result<()> {
        Self::store_string(Self::key_server_device_id(user_did), device_id).await
    }

    /// Read the server-minted device ID. The legacy `device_uuid` slot is not
    /// consulted: it is ambiguous after the local/server split and therefore
    /// must never authorize a device or a publish request.
    pub async fn get_server_device_id(&self, user_did: &str) -> Result<Option<String>> {
        Self::get_string(Self::key_server_device_id(user_did)).await
    }

    /// Remove device authority material while retaining the local UUID for a
    /// later exact `listDevices` reconciliation.
    pub async fn clear_server_device_authority(&self, user_did: &str) -> Result<()> {
        Self::delete_key(Self::key_server_device_id(user_did))?;
        Self::delete_key(Self::key_device_uuid(user_did))?;
        Ok(())
    }

    /// Check the exact consistency of the credential enrollment tuple.
    pub fn check_credential_state(user_did: &str) -> Result<CredentialEnrollmentState> {
        #[cfg(target_os = "android")]
        {
            let _ = user_did;
            Ok(CredentialEnrollmentState::Unenrolled)
        }

        #[cfg(not(target_os = "android"))]
        {
            let slots = [
                ("signing_key", Self::key_signing(user_did)),
                ("mls_did", Self::key_mls_did(user_did)),
                ("server_device_id", Self::key_server_device_id(user_did)),
                ("local_device_uuid", Self::key_local_device_uuid(user_did)),
            ];

            let mut present_count = 0;
            let mut missing = Vec::new();
            let mut signing_key_val = None;
            let mut mls_did_val = None;
            let mut server_device_id_val = None;
            let mut local_device_uuid_val = None;

            for (name, key) in &slots {
                let entry = Self::entry(key).map_err(|e| {
                    OrchestratorError::Credential(format!("keychain access failed for {key}: {e}"))
                })?;
                match entry.get_password() {
                    Ok(pwd) => {
                        let trimmed = pwd.trim().to_string();
                        if trimmed.is_empty() {
                            return Err(OrchestratorError::Credential(format!(
                                "keychain credential slot {key} is empty or corrupt"
                            )));
                        }
                        match *name {
                            "signing_key" => {
                                use base64::engine::general_purpose::STANDARD as B64;
                                use base64::Engine;
                                let decoded = B64.decode(&trimmed).map_err(|e| {
                                    OrchestratorError::Credential(format!(
                                        "invalid base64 in signing_key: {e}"
                                    ))
                                })?;
                                let val: serde_json::Value = serde_json::from_slice(&decoded)
                                    .map_err(|e| {
                                        OrchestratorError::Credential(format!(
                                            "invalid SignatureKeyPair JSON in signing_key: {e}"
                                        ))
                                    })?;
                                let pk_val = val
                                    .get("public")
                                    .and_then(|p| p.as_array())
                                    .ok_or_else(|| {
                                        OrchestratorError::Credential(
                                            "missing or invalid public field in SignatureKeyPair"
                                                .to_string(),
                                        )
                                    })?;
                                let expected_pk: Vec<u8> = pk_val
                                    .iter()
                                    .filter_map(|v| v.as_u64().and_then(|n| u8::try_from(n).ok()))
                                    .collect();
                                if expected_pk.len() != 32 {
                                    return Err(OrchestratorError::Credential(format!(
                                        "signing_key has invalid public key length: expected 32, got {}",
                                        expected_pk.len()
                                    )));
                                }
                                catbird_mls::validate_serialized_signer_keypair_coherence(
                                    &decoded,
                                    &expected_pk,
                                )
                                .map_err(|e| {
                                    OrchestratorError::Credential(format!(
                                        "signing_key coherence validation failed: {e}"
                                    ))
                                })?;
                                signing_key_val = Some(expected_pk);
                            }
                            "mls_did" => {
                                mls_did_val = Some(trimmed);
                            }
                            "server_device_id" => {
                                server_device_id_val = Some(trimmed);
                            }
                            "local_device_uuid" => {
                                local_device_uuid_val = Some(trimmed);
                            }
                            _ => {}
                        }
                        present_count += 1;
                    }
                    Err(keyring::Error::NoEntry) => {
                        missing.push(*name);
                    }
                    Err(e) => {
                        return Err(OrchestratorError::Credential(format!(
                            "keychain read failed for {key}: {e}"
                        )));
                    }
                }
            }

            if present_count == slots.len() {
                let norm_did = crate::keys::normalize_did(user_did);
                let mls_did = mls_did_val.unwrap();
                let local_uuid = local_device_uuid_val.unwrap();
                let server_id = server_device_id_val.unwrap();

                let parsed_local_uuid = uuid::Uuid::parse_str(&local_uuid).map_err(|e| {
                    OrchestratorError::Credential(format!(
                        "local_device_uuid is not a valid UUID: {e}"
                    ))
                })?;
                let local_uuid_canonical = parsed_local_uuid.to_string();

                let parsed_server_id = uuid::Uuid::parse_str(&server_id).map_err(|e| {
                    OrchestratorError::Credential(format!(
                        "server_device_id is not a valid UUID: {e}"
                    ))
                })?;
                let server_id_canonical = parsed_server_id.to_string();

                if server_id_canonical != local_uuid_canonical {
                    return Err(OrchestratorError::Credential(format!(
                        "server_device_id `{server_id_canonical}` does not match local_device_uuid `{local_uuid_canonical}`"
                    )));
                }

                // mls_did must be exact {normalized_did}#{uuid} matching the valid local UUID
                let expected_mls_did = format!("{norm_did}#{local_uuid_canonical}");
                if mls_did != expected_mls_did {
                    return Err(OrchestratorError::Credential(format!(
                        "mls_did binding mismatch: expected `{expected_mls_did}`, found `{mls_did}`"
                    )));
                }
                // Verify that the exact signer slot bound to signing_key exists in keychain
                if let Some(ref pk) = signing_key_val {
                    let slot_prefix =
                        catbird_mls::canonical_signer_keychain_key(pk).map_err(|e| {
                            OrchestratorError::Credential(format!(
                                "failed to derive canonical slot key: {e}"
                            ))
                        })?;
                    let account_id = crate::keys::derive_account_id(&norm_did);
                    let expected_slot_name =
                        format!("{slot_prefix}:{account_id}:{}", crate::keychain::KEY_SUFFIX);

                    // Check that expected_slot_name is a member of the parsed exact account signer index
                    let idx_key =
                        crate::keychain::KeyringKeychainAccess::index_key_for_account(&account_id);
                    let idx_entry = keyring::Entry::new(crate::keychain::SERVICE_NAME, &idx_key)
                        .map_err(|e| {
                            OrchestratorError::Credential(format!(
                                "keychain access failed for signer index: {e}"
                            ))
                        })?;
                    let index: std::collections::BTreeSet<String> = match idx_entry.get_password() {
                        Ok(json_str) => {
                            let trimmed = json_str.trim();
                            if trimmed.is_empty() {
                                return Err(OrchestratorError::Credential(
                                    "signer slots index is empty in keychain".into(),
                                ));
                            }
                            serde_json::from_str(trimmed).map_err(|e| {
                                OrchestratorError::Credential(format!(
                                    "corrupt signer slots index JSON: {e}"
                                ))
                            })?
                        }
                        Err(keyring::Error::NoEntry) => {
                            return Err(OrchestratorError::Credential(format!(
                                "signer index missing for enrolled account `{account_id}`"
                            )));
                        }
                        Err(e) => {
                            return Err(OrchestratorError::Credential(format!(
                                "failed to read signer index: {e}"
                            )));
                        }
                    };

                    if !index.contains(&expected_slot_name) {
                        return Err(OrchestratorError::Credential(format!(
                            "signer slot `{expected_slot_name}` is missing from signer index"
                        )));
                    }

                    let slot_entry =
                        keyring::Entry::new(crate::keychain::SERVICE_NAME, &expected_slot_name)
                            .map_err(|e| {
                                OrchestratorError::Credential(format!(
                                    "keychain access failed for slot: {e}"
                                ))
                            })?;
                    match slot_entry.get_password() {
                        Ok(val) => {
                            if val.trim().is_empty() {
                                return Err(OrchestratorError::Credential(format!(
                                    "signer slot `{expected_slot_name}` is empty"
                                )));
                            }
                        }
                        Err(keyring::Error::NoEntry) => {
                            return Err(OrchestratorError::Credential(format!(
                                "signer slot `{expected_slot_name}` bound to signing_key is missing from keychain"
                            )));
                        }
                        Err(e) => {
                            return Err(OrchestratorError::Credential(format!(
                                "failed to read signer slot `{expected_slot_name}`: {e}"
                            )));
                        }
                    }
                }
                Ok(CredentialEnrollmentState::FullyEnrolled)
            } else if present_count == 0 {
                Ok(CredentialEnrollmentState::Unenrolled)
            } else {
                Ok(CredentialEnrollmentState::Partial(format!(
                    "missing required slots: {}",
                    missing.join(", ")
                )))
            }
        }
    }

    /// Delete all 5 deterministic credentials for this exact user DID / account ID.
    pub fn delete_exact_account_credentials(user_did: &str) -> Result<()> {
        #[cfg(target_os = "android")]
        {
            let _ = user_did;
            Err(OrchestratorError::Credential(
                "Android secure credential storage is not implemented; refusing to clear via keyring".to_string(),
            ))
        }

        #[cfg(not(target_os = "android"))]
        {
            Self::delete_key(Self::key_signing(user_did))?;
            Self::delete_key(Self::key_mls_did(user_did))?;
            Self::delete_key(Self::key_device_uuid(user_did))?;
            Self::delete_key(Self::key_server_device_id(user_did))?;
            Self::delete_key(Self::key_local_device_uuid(user_did))?;
            Ok(())
        }
    }
}

#[async_trait]
impl CredentialStore for KeyringCredentialStore {
    async fn store_signing_key(&self, user_did: &str, key_data: &[u8]) -> Result<()> {
        if key_data.is_empty() {
            return Err(OrchestratorError::Credential(
                "cannot persist an empty signing key".to_string(),
            ));
        }
        use base64::Engine;
        let encoded = base64::engine::general_purpose::STANDARD.encode(key_data);
        Self::entry(&Self::key_signing(user_did))
            .map_err(|e| OrchestratorError::Credential(e.to_string()))?
            .set_password(&encoded)
            .map_err(|e| OrchestratorError::Credential(e.to_string()))
    }

    async fn get_signing_key(&self, user_did: &str) -> Result<Option<Vec<u8>>> {
        use base64::Engine;
        match Self::entry(&Self::key_signing(user_did)) {
            Ok(entry) => match entry.get_password() {
                Ok(encoded) => {
                    let trimmed = encoded.trim();
                    if trimmed.is_empty() {
                        return Err(OrchestratorError::Credential(
                            "keychain signing key is empty or corrupt".to_string(),
                        ));
                    }
                    let bytes = base64::engine::general_purpose::STANDARD
                        .decode(trimmed)
                        .map_err(|e| OrchestratorError::Credential(e.to_string()))?;
                    if bytes.is_empty() {
                        return Err(OrchestratorError::Credential(
                            "keychain signing key payload is empty or corrupt".to_string(),
                        ));
                    }
                    Ok(Some(bytes))
                }
                Err(keyring::Error::NoEntry) => Ok(None),
                Err(e) => Err(OrchestratorError::Credential(e.to_string())),
            },
            Err(e) => Err(OrchestratorError::Credential(e.to_string())),
        }
    }

    async fn delete_signing_key(&self, user_did: &str) -> Result<()> {
        Self::delete_key(Self::key_signing(user_did))
    }

    async fn store_mls_did(&self, user_did: &str, mls_did: &str) -> Result<()> {
        let mls_did = mls_did.trim();
        if mls_did.is_empty() {
            return Err(OrchestratorError::Credential(
                "cannot persist an empty mls_did".to_string(),
            ));
        }
        Self::entry(&Self::key_mls_did(user_did))
            .map_err(|e| OrchestratorError::Credential(e.to_string()))?
            .set_password(mls_did)
            .map_err(|e| OrchestratorError::Credential(e.to_string()))
    }

    async fn get_mls_did(&self, user_did: &str) -> Result<Option<String>> {
        match Self::entry(&Self::key_mls_did(user_did)) {
            Ok(entry) => match entry.get_password() {
                Ok(val) => {
                    let trimmed = val.trim();
                    if trimmed.is_empty() {
                        Err(OrchestratorError::Credential(
                            "keychain mls_did is empty or corrupt".to_string(),
                        ))
                    } else {
                        Ok(Some(val))
                    }
                }
                Err(keyring::Error::NoEntry) => Ok(None),
                Err(e) => Err(OrchestratorError::Credential(e.to_string())),
            },
            Err(e) => Err(OrchestratorError::Credential(e.to_string())),
        }
    }

    async fn store_device_uuid(&self, user_did: &str, uuid: &str) -> Result<()> {
        self.store_server_device_id(user_did, uuid).await
    }

    async fn get_device_uuid(&self, user_did: &str) -> Result<Option<String>> {
        self.get_server_device_id(user_did).await
    }

    async fn has_credentials(&self, user_did: &str) -> Result<bool> {
        let has_key = self.get_signing_key(user_did).await?.is_some();
        let has_uuid = self.get_device_uuid(user_did).await?.is_some();
        Ok(has_key && has_uuid)
    }

    async fn clear_all(&self, user_did: &str) -> Result<()> {
        Self::delete_exact_account_credentials(user_did)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_uuid_and_server_device_id_use_distinct_keychain_slots() {
        let did = "did:plc:catmos";
        let account_id = derive_account_id(did);
        assert_ne!(
            KeyringCredentialStore::key_local_device_uuid(did),
            KeyringCredentialStore::key_server_device_id(did)
        );
        assert_eq!(
            KeyringCredentialStore::key_local_device_uuid(did),
            format!("local_device_uuid:{}:clean-v2-openmls-v09", account_id)
        );
        assert_eq!(
            KeyringCredentialStore::key_server_device_id(did),
            format!("server_device_id:{}:clean-v2-openmls-v09", account_id)
        );
    }

    #[cfg(target_os = "android")]
    #[test]
    fn android_credential_store_constructor_fails_closed() {
        let err = match KeyringCredentialStore::try_new() {
            Ok(_) => panic!("Android must not use keyring's mock credential store"),
            Err(err) => err,
        };
        assert!(
            err.to_string()
                .contains("Android secure credential storage is not implemented"),
            "unexpected error: {err}"
        );
    }

    #[cfg(not(target_os = "android"))]
    #[test]
    fn non_android_credential_store_constructor_succeeds() {
        let _ =
            KeyringCredentialStore::try_new().expect("desktop credential constructor should work");
    }
}
